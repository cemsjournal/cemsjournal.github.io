  applyDir(lang) {
    const l = lang || this.getLang();
    document.documentElement.lang = l;
    document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
  },

  t(key) {
    const l = this.getLang();
    return (this.dict[l] && this.dict[l][key]) || this.dict.en[key] || key;
  },

